/**
 * Writes scripts/card-contact-sheet.html: every card face in the engine's deck
 * order, each with its code, the engine's name, its colour and the upstream
 * file it came from, then the back. Open the page straight from disk to check
 * the whole deck by eye; it is the acceptance artifact for the card art.
 *
 *   node scripts/card-contact-sheet.mjs          write it
 *   node scripts/card-contact-sheet.mjs --check  fail if it is stale
 */

import { readFileSync, writeFileSync } from "node:fs";
import { SPIRITUAL_DECK, parts } from "../engine/kindredEngine.js";
import { cardCode } from "../src/lib/cardArt.js";

const ROOT = new URL("../", import.meta.url);
const OUT = new URL("card-contact-sheet.html", import.meta.url);
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "\"": "&quot;" }[c]));

export function renderContactSheet() {
  const manifest = JSON.parse(readFileSync(new URL("public/card-art/manifest.json", ROOT), "utf8"));
  const byCode = new Map(manifest.cards.map((c) => [c.code, c]));

  // Index 1..52, then the Joker, which sits at 0 and in neither spread.
  const order = Object.keys(SPIRITUAL_DECK).map(Number).filter((n) => n > 0).sort((a, b) => a - b);
  order.push(0);

  const figure = (src, code, title, note, red) => `      <figure${red ? " class=\"red\"" : ""}>
        <img src="../public/card-art/${esc(src)}" alt="${esc(title)}">
        <figcaption><b>${esc(code)}</b>${esc(title)}<small>${esc(note)}</small></figcaption>
      </figure>`;

  const faces = order.map((n) => {
    const name = SPIRITUAL_DECK[n];
    const code = cardCode(name);
    const entry = byCode.get(code);
    if (!entry) throw new Error(`no art in the manifest for ${name} (${code})`);
    const red = parts(name).red;
    return figure(entry.file, code, name, `${entry.upstream} · ${red ? "red" : "black"}`, red);
  });
  const back = figure(manifest.back.file, manifest.back.code, "Card back", "drawn for this repo", false);

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="robots" content="noindex, nofollow">
  <!-- GENERATED by scripts/card-contact-sheet.mjs. Do not edit by hand. -->
  <title>Card art contact sheet, ${esc(manifest.version)}</title>
  <style>
    :root{--felt:#0E241C; --felt-3:#16342A; --ivory:#F3EEE2; --mute:#87A196}
    body{margin:0; padding:20px 24px 32px; background:var(--felt); color:var(--ivory);
      font:13px/1.45 Inter, system-ui, sans-serif}
    h1{font-family:'Bodoni Moda', Georgia, serif; font-size:22px; margin:0 0 4px}
    p{color:var(--mute); margin:0 0 16px; max-width:900px}
    .deck{display:grid; grid-template-columns:repeat(13, minmax(0, 1fr)); gap:12px 8px}
    figure{margin:0; text-align:center; min-width:0}
    img{display:block; width:100%; height:auto}
    figcaption{margin-top:4px; font-size:10.5px; line-height:1.3}
    figcaption b{display:block; font-size:12.5px}
    figcaption small{display:block; color:var(--mute); font-size:9.5px; overflow-wrap:anywhere}
    .red b{color:#E58A8A}
  </style>
</head>
<body>
  <h1>Card art contact sheet, ${esc(manifest.version)}</h1>
  <p>All ${manifest.cards.length} faces in the engine's deck order, then the back. Under each: the code, the
    engine's name, and the upstream file that became it. Source: ${esc(manifest.source.name)} by
    ${esc(manifest.source.author)}, ${esc(manifest.source.license.toLowerCase())}.</p>
  <main class="deck">
${faces.join("\n")}
${back}
  </main>
</body>
</html>
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const html = renderContactSheet();
  if (process.argv.includes("--check")) {
    const onDisk = readFileSync(OUT, "utf8");
    if (onDisk !== html) { console.error("contact sheet is stale; rerun node scripts/card-contact-sheet.mjs"); process.exit(1); }
    console.log("contact sheet: current");
  } else {
    writeFileSync(OUT, html);
    console.log(`contact sheet: wrote ${OUT.pathname}`);
  }
}
