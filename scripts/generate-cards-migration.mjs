/**
 * Writes the cards migration from the engine's own card names.
 *
 *   node scripts/generate-cards-migration.mjs          write or refresh it
 *   node scripts/generate-cards-migration.mjs --check  fail if it has drifted
 *
 * The names come from SPIRITUAL_DECK (the engine's spiritualCardName output
 * for every index) and rank, suit and colour from parts(), so the table cannot
 * disagree with the engine through a typo. Rows are written in code order:
 * the migration carries names only, never the engine's deck order or indices.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { SPIRITUAL_DECK, JOKER, parts } from "../engine/kindredEngine.js";

const DIR = new URL("../supabase/migrations/", import.meta.url).pathname;
const DEFAULT_FILE = "20260915162458_cards.sql";
const SUIT_CODE = { Hearts: "H", Clubs: "C", Diamonds: "D", Spades: "S" };
const IMAGE_PREFIX = "v1";

function fail(message) {
  console.error(`cards: ${message}`);
  process.exit(1);
}

function buildRows() {
  const names = [...new Set(Object.values(SPIRITUAL_DECK))];
  if (names.length !== 53) fail(`expected 53 distinct names from the engine, got ${names.length}`);
  if (!names.includes(JOKER)) fail("the engine's deck has no Joker");

  const rows = names.map((name) => {
    const p = parts(name);
    if (name === JOKER) {
      return { code: "JOK", name, rank: p.rank, suit: null, isRed: p.red };
    }
    if (!(p.suit in SUIT_CODE) || !p.rank) fail(`cannot split "${name}"`);
    const code = `${p.rank}${SUIT_CODE[p.suit]}`;
    return { code, name, rank: p.rank, suit: p.suit, isRed: p.red };
  });

  const codes = new Set(rows.map((r) => r.code));
  if (codes.size !== rows.length) fail("two cards share a code");
  for (const r of rows) {
    const red = r.suit === "Hearts" || r.suit === "Diamonds";
    if (r.isRed !== red) fail(`${r.code} colour does not match its suit`);
  }
  return rows.sort((a, b) => a.code.localeCompare(b.code, "en"));
}

const lit = (v) => (v === null ? "null" : typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

function render(rows) {
  const values = rows
    .map((r) => `  (${[r.code, r.name, r.rank, r.suit, r.isRed, `${IMAGE_PREFIX}/${r.code}.svg`].map(lit).join(", ")})`)
    .join(",\n");

  return `-- Cards: the 52 cards and the Joker, with where each face's art lives.
--
-- GENERATED by scripts/generate-cards-migration.mjs from the engine's own card
-- names. Do not edit by hand; rerun the script, and \`--check\` catches drift.
-- image_path is relative to the card-art Storage bucket.

create table public.cards (
  code       text primary key,
  name       text not null unique,
  rank       text not null,
  suit       text,
  is_red     boolean not null,
  image_path text not null unique,
  created_at timestamptz not null default now(),
  constraint cards_suit check (suit in ('Hearts', 'Clubs', 'Diamonds', 'Spades')),
  constraint cards_joker_has_no_suit check ((code = 'JOK') = (suit is null)),
  constraint cards_red_matches_suit check (is_red = coalesce(suit in ('Hearts', 'Diamonds'), false))
);

insert into public.cards (code, name, rank, suit, is_red, image_path) values
${values};

-- Reference data. Readable without an account so the demo build can use it.
alter table public.cards enable row level security;

revoke all on public.cards from anon, authenticated;
grant select on public.cards to anon, authenticated;

create policy "cards: anyone may read the deck"
  on public.cards for select to anon, authenticated
  using (true);
`;
}

const existing = readdirSync(DIR).find((f) => /_cards\.sql$/.test(f));
const file = join(DIR, existing ?? DEFAULT_FILE);
const sql = render(buildRows());

if (process.argv.includes("--check")) {
  let onDisk = "";
  try { onDisk = readFileSync(file, "utf8"); } catch { fail(`${file} is missing; run the generator`); }
  if (onDisk !== sql) fail(`${file} has drifted from the engine; rerun the generator`);
  console.log(`cards: ${file} matches the engine (53 rows)`);
} else {
  writeFileSync(file, sql);
  console.log(`cards: wrote ${file}`);
}
